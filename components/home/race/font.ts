const ROWS: Record<string, string[]> = Object.fromEntries(Object.entries(GLYPHS).map(([ch, rows]) => [ch, rows.split("/")]));

/** width in pixels of `text` at `scale` (glyphs are 5 wide with 1 pixel between them) */
export const textWidth = (text: string, scale = 1): number => (text.length * 6 - 1) * scale;

/**
 * Draws pixel text with its top-left corner at (x, y). `color` is either a CSS colour or a function
 * of the horizontal position 0..1, which is how the Solana gradient text is done.
 */
export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string | ((t: number) => string), scale = 1): void {
  const width = textWidth(text, scale);
  for (let i = 0; i < text.length; i++) {
    const rows = ROWS[text[i]];
    if (!rows) continue;
    for (let gx = 0; gx < 5; gx++) {
      const px = x + (i * 6 + gx) * scale;
      ctx.fillStyle = typeof color === "string" ? color : color(width > 0 ? (px - x) / width : 0);
      for (let gy = 0; gy < 7; gy++) if (rows[gy][gx] === "#") ctx.fillRect(px, y + gy * scale, scale, scale);
    }
  }
}
