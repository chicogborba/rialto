interface Overview {
  seller: { name: string; payoutAddress: string; balanceMicro: number; paidOutMicro: number };
  totals: { calls: number; failedNotCharged: number; earnedMicro: number };
  apis: { id: string; slug: string; name: string; status: string; calls: number; earnedMicro: number; services: { capability: string; sellerPriceMicro: number; buyerPriceMicro: number }[] }[];
  minPayoutMicro: number;
}
interface Quote {
  youEarnUsd?: number;
  platformFeeUsd?: number;
  buyersPayUsd?: number;
  fee: { bps: number; minUsd: number };
}
interface TestResult {
  ok: boolean;
  latencyMs: number;
  result?: unknown;
  error?: string;
}

type Draft = { name: string; description: string; capability: CapabilityId; upstreamUrl: string; method: "GET" | "POST"; bodyTemplate: string; headerName: string; headerValue: string; resultPick: string; priceUsd: string; quality: string; latencyMs: string };
const BLANK: Draft = { name: "", description: "", capability: "data.lookup", upstreamUrl: "", method: "GET", bodyTemplate: "", headerName: "", headerValue: "", resultPick: "", priceUsd: "0.01", quality: "85", latencyMs: "400" };

/** Ready-made drafts, so the whole flow can be tried without an API of your own. */
