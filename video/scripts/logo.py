"""Rialto's logo, drawn in code: writes the SVG files for the site and the same shapes for the video.

    python3 video/scripts/logo.py

The mark is a heavy R with a route running through it: one lime node (the agent), two orange ones
(Rialto, then the API it hires). The wordmark is lettered to match, so nothing depends on a font.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INK, CREAM, LIME, ORANGE = "#17120f", "#f6efe0", "#c6ff3d", "#ee7a35"

# ---- the mark, in a 100 x 100 box
R_OUTLINE = "M3 3H72L93 21V42L80 54L97 71V97H65L39 71V38L29 48V97H3Z"
# the route, as two legs so each can be drawn on its own: agent -> Rialto, Rialto -> API
ROUTE = ["M16 16H40L48 24V50", "M48 50L84 86"]
ARROWS = ["M30.5 10.5L36 16L30.5 21.5", "M64.5 74.5H72.5V66.5"]
NODES = [(16, 16, LIME), (48, 50, ORANGE), (84, 86, ORANGE)]
NODE = 15


def node(x, y):
    return f'x="{x - NODE / 2:g}" y="{y - NODE / 2:g}" width="{NODE}" height="{NODE}" rx="2.6"'


# ---- the wordmark: cap height 100, x-height from y = 30, stems 24 wide
GLYPHS = [
    # R
    (0, "M0 3a3 3 0 0 1 3-3H54A24 24 0 0 1 78 24V38A24 24 0 0 1 61 61L84 100H56L37 64H24V97a3 3 0 0 1-3 3H3a3 3 0 0 1-3-3ZM24 20H48A6 6 0 0 1 54 26V36A6 6 0 0 1 48 42H24Z"),
    # i
    (93, "M3 0H21a3 3 0 0 1 3 3V17a3 3 0 0 1-3 3H3a3 3 0 0 1-3-3V3a3 3 0 0 1 3-3ZM3 30H21a3 3 0 0 1 3 3V97a3 3 0 0 1-3 3H3a3 3 0 0 1-3-3V33a3 3 0 0 1 3-3Z"),
    # a
    (126, "M7 30H54A18 18 0 0 1 72 48V97a3 3 0 0 1-3 3H18A18 18 0 0 1 0 82V75A17 17 0 0 1 17 58H48V48H7a3 3 0 0 1-3-3V33a3 3 0 0 1 3-3ZM29 72H48V86H29a5 5 0 0 1-5-5V77a5 5 0 0 1 5-5Z"),
    # l
    (207, "M3 0H21a3 3 0 0 1 3 3V97a3 3 0 0 1-3 3H3a3 3 0 0 1-3-3V3a3 3 0 0 1 3-3Z"),
    # t
    (240, "M13 8H31a3 3 0 0 1 3 3V30H47a3 3 0 0 1 3 3V45a3 3 0 0 1-3 3H34V77a5 5 0 0 0 5 5H47a3 3 0 0 1 3 3V97a3 3 0 0 1-3 3H30A20 20 0 0 1 10 80V48H3a3 3 0 0 1-3-3V33a3 3 0 0 1 3-3H10V11a3 3 0 0 1 3-3Z"),
    # o
    (298, "M24 30H52A24 24 0 0 1 76 54V76A24 24 0 0 1 52 100H24A24 24 0 0 1 0 76V54A24 24 0 0 1 24 30ZM32 50H44a8 8 0 0 1 8 8V72a8 8 0 0 1-8 8H32a8 8 0 0 1-8-8V58a8 8 0 0 1 8-8Z"),
]
WORD_W = 374
# the lockup: mark at full height, wordmark at 0.62 of it, optically centred
SCALE, GAP = 0.62, 26
WORD_X, WORD_Y = 100 + GAP, (100 - 100 * SCALE) / 2 + 1
LOCKUP_W = WORD_X + WORD_W * SCALE


def mark(fg=INK, route=CREAM):
    out = [f'<path d="{R_OUTLINE}" fill="{fg}" stroke="{fg}" stroke-width="6" stroke-linejoin="round"/>']
    out += [f'<path d="{d}" fill="none" stroke="{route}" stroke-width="5" stroke-linecap="round" stroke-linejoin="round"/>' for d in ROUTE]
    out += [f'<path d="{d}" fill="none" stroke="{route}" stroke-width="4" stroke-linecap="round" stroke-linejoin="round"/>' for d in ARROWS]
    out += [f'<rect {node(x, y)} fill="{c}"/>' for x, y, c in NODES]
    return "\n  ".join(out)


def word(fg=INK):
    letters = "".join(f'<path transform="translate({x})" d="{d}"/>' for x, d in GLYPHS)
    return f'<g transform="translate({WORD_X:g} {WORD_Y:g}) scale({SCALE})" fill="{fg}" fill-rule="evenodd">{letters}</g>'


def svg(w, body, label="Rialto"):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w:g} 100" role="img" aria-label="{label}">\n  {body}\n</svg>\n'


brand = ROOT / "public/brand"
brand.mkdir(parents=True, exist_ok=True)
(brand / "rialto-mark.svg").write_text(svg(100, mark()))
(brand / "rialto-logo.svg").write_text(svg(LOCKUP_W, mark() + "\n  " + word()))
(brand / "rialto-logo-dark.svg").write_text(svg(LOCKUP_W, mark(CREAM, INK) + "\n  " + word(CREAM)))

ts = f'''// Generated by scripts/logo.py: the same shapes as public/brand/rialto-*.svg. Edit the script, not this file.
export const LOGO = {{
  outline: "{R_OUTLINE}",
  route: {ROUTE!r},
  arrows: {ARROWS!r},
  nodes: {[list(n) for n in NODES]!r},
  nodeSize: {NODE},
  glyphs: {[list(g) for g in GLYPHS]!r},
  wordWidth: {WORD_W},
  wordScale: {SCALE},
  wordX: {WORD_X:g},
  wordY: {WORD_Y:g},
  lockupWidth: {LOCKUP_W:g},
}} as const;
'''.replace("'", '"')
(ROOT / "video/src/ui/logo-paths.ts").write_text(ts)
print("wrote", LOCKUP_W)
